def rank(cands: list[Candidate], recency_ablation: bool = False) -> list[Candidate]:
    out = []
    for c in cands:
        c2 = Candidate(**{k: getattr(c, k) for k in c.__dataclass_fields__})
        if recency_ablation:
            c2.recency = 0.5  # flatten recency so a 2026 scoop cannot buy the class
        c2.score = efc_score(c2)
        if recency_ablation:
            c2.ablation_score = c2.score
        if c2.status == "CONTROL":
            c2.verdict = "CONTROL — must stay 0 or class is void"
        elif c2.status == "ZEROED" or c2.score == 0:
            c2.verdict = f"ZEROED ({c2.overlap_class or 'spoken/reclaim'})"
        elif c2.overlap_kind == "framed_by":
            c2.verdict = f"ELIGIBLE remainder after {c2.overlap_class}"
        else:
            c2.verdict = "ELIGIBLE — no archive overlap"
        out.append(c2)
    out.sort(key=lambda x: (-x.score, x.id))
    return out


def spearman(xs: list[float], ys: list[float]) -> float:
    """Spearman rho without scipy. Ties get average ranks."""
    if len(xs) != len(ys) or len(xs) < 3:
        raise ValueError("need >=3 paired observations")

    def ranks(a: list[float]) -> list[float]:
        n = len(a)
        order = sorted(range(n), key=lambda i: a[i])
        r = [0.0] * n
        i = 0
        while i < n:
            j = i
            while j + 1 < n and a[order[j + 1]] == a[order[i]]:
                j += 1
            avg = (i + j) / 2.0 + 1.0
            for k in range(i, j + 1):
                r[order[k]] = avg
            i = j + 1
        return r

    rx, ry = ranks(xs), ranks(ys)
    mx, my = sum(rx) / len(rx), sum(ry) / len(ry)
    num = sum((a - mx) * (b - my) for a, b in zip(rx, ry))
    denx = math.sqrt(sum((a - mx) ** 2 for a in rx))
    deny = math.sqrt(sum((b - my) ** 2 for b in ry))
    if denx == 0 or deny == 0:
        return 0.0
    return num / (denx * deny)


