def validate_unit(name: str, x: float) -> float:
    if not isinstance(x, (int, float)) or isinstance(x, bool):
        raise TypeError(f"{name} must be numeric, got {type(x)}")
    if math.isnan(x) or math.isinf(x):
        raise ValueError(f"{name} not finite: {x}")
    if x < 0.0 or x > 1.0:
        raise ValueError(f"{name} must be in [0, 1], got {x}")
    return float(x)


def efc_score(c: Candidate) -> float:
    """Score an EFC candidate.

    Inputs are unit-interval heuristic weights, not physical measurements.
    Zeroed/control/spoken/reclaim rows return 0.

    Returns a non-negative heuristic. Higher = more remaining EFC surface
    after archive subtraction.
    """
    if c.status in {"ZEROED", "CONTROL"}:
        return 0.0
    if c.spoken:
        return 0.0
    if c.overlap_kind == "reclaim_of":
        return 0.0

    m = validate_unit("more_n_invariance", c.more_n_invariance)
    g = validate_unit("generator_split", c.generator_split)
    s = validate_unit("sourcedness", c.sourcedness)
    r = validate_unit("recency", c.recency)

    tax = 0.0
    if c.overlap_kind == "framed_by":
        tax = validate_unit("framed_tax", c.framed_tax)

    # Product of the four operators, then archive tax.
    raw = (m**1.15) * (g**1.10) * s * (0.55 + 0.45 * r)
    return round(raw * (1.0 - tax) * 100.0, 4)


def more_n_closes(c: Candidate, extra_n_from: str) -> bool:
    """Return True only if adding samples from extra_n_from would identify G_target.

    Edge cases:
      - extra_n_from must be g_cal or g_target
      - reclaim/zeroed rows are not testable as EFC
    """
    if extra_n_from not in {c.g_cal, c.g_target}:
        raise ValueError("extra_n_from must be g_cal or g_target")
    if c.status != "ELIGIBLE":
        return False
    if extra_n_from == c.g_target:
        # Sampling the target generator can close EFC (and may look like
        # undersampling of G_target). That is the discriminator, not the class.
        return True
    # extra_n_from == g_cal
    return c.more_n_invariance < 0.5


def sigma_separation(x: float, mu: float, sigma: float) -> float:
    """Signed separation of a point from a reference mean, in units of sigma.

    Used only as a citation-check for published 3I/ATLAS numbers.
    """
    if sigma <= 0:
        raise ValueError("sigma must be positive")
    return (x - mu) / sigma


